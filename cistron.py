def _norm_key(v):
    return str(v).strip().lower().replace(" ", "_") if v is not None else ""


def _as_bool(v, default=False):
    if v is None or str(v).strip() == "":
        return default
    if isinstance(v, bool):
        return v
    return str(v).strip().lower() in TRUTHY


def _as_float(v, default=None):
    if v is None or str(v).strip() == "":
        return default
    try:
        return float(str(v).strip().replace(",", "."))
    except ValueError:
        raise ValueError(f"Expected a number, got {v!r}")


def _sheet_rows(ws, expect=()):
    """Yield dicts keyed by the header row.

    The header is not assumed to be row 1: a sheet may carry a block of
    explanation above its table, which is where a reader actually looks.
    The first row containing one of `expect` wins; failing that, row 1."""
    grid = list(ws.iter_rows(values_only=True))
    if not grid:
        return
    head_i = 0
    if expect:
        want = {e.lower() for e in expect}
        for i, row in enumerate(grid[:40]):
            cells = {_norm_key(c) for c in row if c is not None}
            if cells & want:
                head_i = i
                break
    header = [_norm_key(h) for h in grid[head_i]]
    for r in grid[head_i + 1:]:
        if all(c is None or str(c).strip() == "" for c in r):
            continue
        yield {h: v for h, v in zip(header, r) if h}


TEXT_SETTINGS = ("outfile", "anchor_side", "export_prefix", "theme", "style",
                 "palette", "palette_mode", "labels", "show_legend",
                 "label_repeat", "row_titles")


def load_workbook_config(path):
    try:
        from openpyxl import load_workbook
    except ImportError:
        raise SystemExit("openpyxl is needed to read Excel files.\n"
                         "Install it with:  python3 -m pip install openpyxl")

    base = os.path.dirname(os.path.abspath(path))
    wb = load_workbook(path, data_only=True)
    names = {n.strip().lower(): n for n in wb.sheetnames}

    settings = dict(SETTINGS)
    # relative outputs land beside the workbook, not beside the script
    settings["_basedir"] = base
    if "settings" in names:
        for r in _sheet_rows(wb[names["settings"]], ("setting", "value")):
            k = _norm_key(r.get("setting"))
            if not k or k.startswith("_") or k not in settings:
                continue
            v = r.get("value")
            if v is None or str(v).strip() == "":
                continue
            if isinstance(settings[k], bool):
                settings[k] = _as_bool(v)
            elif k in TEXT_SETTINGS:
                settings[k] = str(v).strip()
            else:
                settings[k] = _as_float(v)
    if settings["figure_height_cm"] == 0:
        settings["figure_height_cm"] = None
    if str(settings["anchor_side"]).lower() not in ("left", "right"):
        raise SystemExit(f"anchor_side must be 'left' or 'right', got {settings['anchor_side']!r}")
    pm = str(settings["palette_mode"]).strip().lower()
    if pm == "sheet":
        pm = "auto"               # the older spelling
    if pm not in ("auto", "theme"):
        raise SystemExit("palette_mode must be 'auto' or 'theme'")
    settings["palette_mode"] = pm

    colors = {}
    if "colors" in names:
        for r in _sheet_rows(wb[names["colors"]], ("name", "hex")):
            nm, hx = r.get("name"), r.get("hex")
            if nm is None or hx is None:
                continue
            nm, hx = str(nm).strip(), str(hx).strip()
            if not nm or not hx:
                continue
            if hx.strip().lower() in ("auto", "automatic", "-"):
                continue          # explicitly released back to the palette
            hx = check_hex(hx, f"colors sheet, row for {nm!r}")
            colors[ALIASES.get(nm.lower(), nm)] = hx
            colors[nm] = hx

    if "cassettes" not in names:
        raise SystemExit(f"{os.path.basename(path)} has no 'cassettes' sheet.")

    groups, seen_order = {}, []
    carried = None          # last cassette name seen, for blank cells
    for i, r in enumerate(_sheet_rows(wb[names["cassettes"]],
                                      ("cassette", "type", "label")), start=2):
        t_raw = r.get("type")
        if t_raw is None or str(t_raw).strip() == "":
            continue
        t_raw = str(t_raw).strip()
        t = ALIASES.get(t_raw.lower())
        if t is None:
            raise SystemExit(
                f"cassettes sheet row {i}: unknown type {t_raw!r}.\n"
                f"Known types: {', '.join(sorted(PART_TYPES))}\n"
                f"Accepted spellings: {', '.join(sorted(ALIASES))}")
        # A blank cassette cell means "same as the row above" - the usual
        # spreadsheet habit of naming a group once. Repeating the name on
        # every row works exactly as before.
        cass = r.get("cassette")
        cass = str(cass).strip() if cass is not None else ""
        if cass:
            carried = cass
        elif carried is None:
            carried = "cassette 1"
        cass = carried

        size = r.get("size")
        size = str(size).strip().upper() if size is not None and str(size).strip() else None
        if size and size not in SIZE_W:
            raise SystemExit(f"cassettes sheet row {i}: size must be XS, S, M or L, got {size!r}")

        d = str(r.get("dir") or "fwd").strip().lower()
        d = "rev" if d in ("rev", "reverse", "r", "-") else "fwd"

        color = str(r.get("color") or "").strip()
        if color:
            color = check_hex(color, f"cassettes sheet row {i}, color column")

        order = r.get("order")
        try:
            order = float(order) if order is not None and str(order).strip() else len(seen_order)
        except ValueError:
            raise SystemExit(f"cassettes sheet row {i}: order must be a number, got {order!r}")

        if cass not in groups:
            groups[cass] = []
            seen_order.append(cass)
        groups[cass].append({"type": t, "label": str(r.get("label") or "").strip(),
                             "size": size, "dir": d, "join": _as_bool(r.get("join")),
                             "color": color, "_o": order, "_row": i})

    constructs = [{"name": c, "parts": sorted(groups[c], key=lambda p: (p["_o"], p["_row"]))}
                  for c in seen_order]
    if not constructs:
        raise SystemExit("cassettes sheet has no usable rows.")
    return settings, colors, constructs


# ------------------------ palette assignment -----------------------------
# How far apart two automatically chosen colours should be, CIE76. Below
# about 20 a reader reads them as the same colour at glyph size.
COLOUR_SPACING = 26.0


def extend_palette(palette, needed):
    """Grow a palette to `needed` colours without leaving its character.

    A palette of 10 cannot colour 14 parts, and repeating one means two
    different genes look identical. Lighter and darker versions of the
    palette's own hues stay recognisably part of the same scheme while
    being clearly distinguishable, which is what the figure needs."""
    out = list(palette)
    if not out or needed <= len(out):
        return out
    # waves of tints and shades, widest first so the earliest extras are
    # the most distinct
    for factor, toward in ((0.50, "#FFFFFF"), (0.55, None), (0.26, "#FFFFFF"),
                           (0.76, None), (0.72, "#FFFFFF")):
        for base in palette:
            if len(out) >= needed:
                return out
            cand = mix(base, toward, factor) if toward else darken(base, factor)
            if all(colour_distance(cand, c) >= COLOUR_SPACING * 0.7 for c in out):
                out.append(cand)
    return out


def assign_palette(constructs, colors, palette, mode):
    """Give every (type, label) a colour.

    Colour is automatic by default. The order of precedence is:

        1. the per-row `color` cell          - always wins
        2. the colors sheet                  - unless mode is "theme"
        3. the active palette, automatically

    The automatic step is deterministic in the LABEL, not in where the part
    happens to appear. Assigning in order of first appearance meant that
    inserting one construct at the top, or sorting the sheet, silently
    recoloured everything below it - so a figure you had already published
    came back different. Here each label hashes to a preferred slot and
    probes forward if that slot is taken, which means:

      - the same gene keeps its colour when you add, remove or reorder rows
      - the same gene gets the same colour in every figure drawn from the
        same palette, so a set of figures agrees with itself
      - nothing shifts just because you renamed a different part

    Pinning a label in the colors sheet overrides all of this; writing
    `auto` there releases it back to the palette.
    """
    import hashlib

    # what still needs a colour, and what is already pinned
    need, resolved = [], {}
    for c in constructs:
        for p in c["parts"]:
            key = (p["type"], p.get("label", ""))
            if key in resolved or key in need:
                continue
            pinned = colors.get(p["label"]) if p.get("label") else None
            if pinned is None and mode != "theme":
                pinned = colors.get(p["type"])
            if pinned and mode != "theme":
                resolved[key] = pinned
            else:
                need.append(key)

    if not palette:
        for key in need:
            resolved[key] = NEUTRAL
        return resolved

    # enough colours for every part, and for anything already pinned, so an
    # automatic colour never lands on a pin either
    pool = extend_palette(palette, len(need) + len(resolved) + 2)
    n = len(pool)
    ordered = sorted(need, key=lambda k: (k[1].lower(), k[0]))

    def slot(key):
        seed = (key[1] or key[0]).lower().encode("utf-8")
        return int.from_bytes(hashlib.sha1(seed).digest()[:4], "big") % n

    # When there are more parts than the pool can hold, spacing is not
    # achievable and checking for it costs O(parts x pool) per part. Fall
    # back to plain hashing: the figure is already past what colour can
    # carry, and the sanity check says so.
    if len(ordered) + len(resolved) > n:
        taken = set()
        for key in ordered:
            start = slot(key)
            pick = next((i for i in ((start + k) % n for k in range(n))
                         if i not in taken), start)
            taken.add(pick)
            resolved[key] = pool[pick]
        return resolved

    pool_lab = [_lab_cached(c) for c in pool]
    used_lab = [_lab_cached(v) for v in resolved.values()]
    for key in ordered:
        start = slot(key)
        best, best_gap = None, -1.0
        for step in range(n):
            i = (start + step) % n
            gap = min((_lab_gap(pool_lab[i], u) for u in used_lab), default=1e9)
            if gap >= COLOUR_SPACING:
                best = i
                break
            if gap > best_gap:            # remember the roomiest fallback
                best, best_gap = i, gap
        used_lab.append(pool_lab[best])
        resolved[key] = pool[best]
    return resolved


