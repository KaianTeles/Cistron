def _wb_last(rows):
    """How far validation, formatting and the filter reach.

    A fixed ceiling silently stopped protecting the sheet once the data grew
    past it, so this tracks the data with room to spare instead."""
    return max(_WB_FLOOR, len(rows or []) + 200)


def _wb_style(bold=False, size=10, color="1A1D20", italic=False):
    from openpyxl.styles import Font
    return Font(bold=bold, size=size, color=color, italic=italic)


def _wb_header(ws, labels, widths, tips=None, row=1):
    """Header row: accent fill, white bold text, a comment per column."""
    from openpyxl.comments import Comment
    from openpyxl.styles import Alignment, PatternFill
    for i, (lab, w) in enumerate(zip(labels, widths), start=1):
        c = ws.cell(row=row, column=i, value=lab)
        c.fill = PatternFill("solid", fgColor=_WB_ACCENT)
        c.font = _wb_style(bold=True, size=11, color="FFFFFF")
        c.alignment = Alignment(horizontal="center", vertical="center")
        ws.column_dimensions[c.column_letter].width = w
        if tips and lab in tips:
            c.comment = Comment(tips[lab], "cistron", height=130, width=320)
    ws.row_dimensions[row].height = 22
    ws.freeze_panes = f"A{row + 1}"


def _wb_validate(ws, cell_range, options=None, source=None, title="", prompt=""):
    """A dropdown that also explains itself when the cell is selected."""
    from openpyxl.worksheet.datavalidation import DataValidation
    f = source if source else '"%s"' % ",".join(options)
    dv = DataValidation(type="list", formula1=f, allow_blank=True,
                        showDropDown=False, showInputMessage=bool(prompt),
                        showErrorMessage=True)
    if prompt:
        dv.promptTitle, dv.prompt = title, prompt
    dv.errorTitle, dv.error = "Not a valid value", prompt or "Pick one from the list."
    ws.add_data_validation(dv)
    dv.add(cell_range)
    return dv


