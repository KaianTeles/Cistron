def check_hex(value, where):
    v = str(value).strip()
    if not v.startswith("#"):
        v = "#" + v
    if not HEX_RE.match(v):
        raise SystemExit(f"{where}: {value!r} is not a colour. Use a hex code "
                         f"like #2C7FB8 (or #28B), with or without the #.")
    return v.upper()

