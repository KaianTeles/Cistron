def is_scalable(p):
    """Does this part's drawn width carry information?

    A CDS, a homology arm or an LTR occupies sequence, so XS..L is a real
    statement about it. A loxP site, an origin, a restriction cut or a PAM
    is a position: drawing one wider asserts something untrue. Point
    features therefore render at a fixed canonical width, ignore the sheet's
    size column, and take an outside label rather than stretching to hold
    text."""
    return PART_TYPES.get(p["type"], {}).get("scale", True)


