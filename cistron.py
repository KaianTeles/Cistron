#!/usr/bin/env python3
"""
cistron.py  --  draw genetic construct/cassette maps as editable SVG.

==========================================================================
                  >>>  YOU DO NOT EDIT THIS FILE  <<<
==========================================================================
Everything lives in the Excel workbook. Put constructs.xlsx next to
this script and run:

    python3 cistron.py                      # uses constructs.xlsx
    python3 cistron.py my_constructs.xlsx   # or name your own file
    python3 cistron.py --themes             # contact sheet of every theme

THEMES
------
One setting changes the whole look. In the settings sheet put

    theme    journal

and the figure is restyled and recoloured in one go. A theme is just a
style + a palette; set either on its own if you want to mix them:

    style    outline
    palette  tol-muted

`python3 cistron.py --list` prints every theme, style and palette.

LABELS
------
`labels` names the glyphs directly and composes with every theme:

    none      legend only
    inside    the name sits in the glyph, which widens to fit it
    outside   the name sits above, stacked in tiers so nothing collides
    below     the same, under the backbone

Promoters, terminators, tags and loxP sites are too thin to hold text, so
under `inside` they take an outside label instead. `show_legend` = auto
drops the legend whenever the glyphs carry their own names.

`label_repeat` controls how often a name is printed:

    all       every glyph (default)
    once      only the first time it appears anywhere in the figure
    row       the first time it appears in each cassette

With `once` the glyph still keeps the width its label would have needed, so
rows of near-identical cassettes stay aligned column to column.

Colour precedence, highest first:
    1. the per-row `color` cell in the cassettes sheet
    2. the colors sheet          (unless palette_mode = theme)
    3. the active palette, assigned in order of first appearance

So a theme recolours everything you have NOT pinned. To let a theme
override your colors sheet as well, set palette_mode to `theme`.

The workbook sheets:
  settings   setting | value. Blank value = built-in default.
  colors     name | hex. Name = a part type (homology_arm, ctp, tag, p2a,
             terminator, loxp, promoter) or an exact label (GFP, pTEF1).
  cassettes  one row per element, in order:
               cassette  grouping key - rows sharing it form one figure row
               order     1, 2, 3 ... within that cassette
               type      HA | prom | cds | ctp | tag | p2a | term | loxp
               label     text shown in the legend
               size      XS | S | M | L
               dir       fwd | rev
               join      yes = flush against the previous element (fusion)
               color     optional hex for this row only
Rows with an empty type are skipped, so blank spacer lines are fine.
"""

