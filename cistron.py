    ws.conditional_formatting.add(f"C2:C{last}", FormulaRule(
        formula=['AND($C2<>"",COUNTIF(lists!$A:$A,$C2)=0)'],
        fill=PatternFill("solid", bgColor="FBD5D5"),
        font=Font(color="9C1C1C", bold=True)))
    # dim the whole row while it has no type (i.e. it is skipped)
    ws.conditional_formatting.add(rng, FormulaRule(
        formula=['AND($C2="",COUNTA($A2:$I2)>0)'],
        font=Font(color="B9C0C5")))
    ws.auto_filter.ref = f"A1:I{last}"



