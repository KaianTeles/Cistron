# Glyphs can carry their own name. Three placements, all of which work with
# every style because they only ever use the style's own ink colours.
#
#   none      legend only (the original behaviour)
#   inside    name set in the middle of the glyph, which grows to fit it
#   outside   name above the glyph, stacked into tiers so nothing collides
#   below     the same, under the backbone - use when promoter arrows crowd
#             the top edge
#
# Shapes that are a line or a sliver have nowhere to put text, so in
# `inside` they fall back to an outside label rather than being squashed.
LABEL_PAD = 7          # breathing room each side of an inside label
TIER_GAP = 4           # vertical space between stacked outside labels

# Rough Helvetica advance widths, as a fraction of the font size. Good to a
# few percent, which is all the layout needs.
_NARROW = set("iltfjI|.,;:'\"`!()[]{}-")
_WIDE = set("mwMW@")


def text_width(txt, px):
    w = 0.0
    for ch in str(txt):
        if ch == " ":
            w += 0.28
        elif ch in _NARROW:
            w += 0.31
        elif ch in _WIDE:
            w += 0.85
        elif ch.isupper():
            w += 0.70
        else:
            w += 0.55
    return w * px


def label_ink(color, st):
    """Text colour that stays readable on whatever fill the style produced."""
    f, _, _ = ink(color, st)
    return "#FFFFFF" if luminance(f) < 0.58 else "#15181B"


def inside_ok(p, mode):
    """Whether this part CAN hold text - independent of whether we choose to
    print it. Width planning uses this so that a repeat whose label is
    suppressed keeps the same width and the rows stay aligned."""
    return (mode == "inside" and is_scalable(p)
            and glyph_of(p) in WRITABLE_GLYPHS and p.get("label"))


def outside_needed(p, mode):
    if not p.get("label"):
        return False
    if mode in ("outside", "below"):
        return True
    if mode == "inside":
        return not (is_scalable(p) and glyph_of(p) in WRITABLE_GLYPHS)
    return False


def top_ink(p, st):
    """How far the glyph's ink reaches above the backbone."""
    g = glyph_of(p)
    if g in GLYPH_RISE:
        return GLYPH_RISE[g] * st["h"]
    return H * st["h"] / 2


# --------------------------- glyphs ---------------------------
def contrast(color, bg, need=0.30):
    """Push a colour away from the background until it is actually visible.
    Without this, a pale palette on white (or a dark one on a dark theme)
    renders as a blank glyph - which is how 'watercolour' and 'print' used
    to come out."""
    lb = luminance(bg)
    for _ in range(14):
        if abs(luminance(color) - lb) >= need:
            break
        color = darken(color, 0.86) if lb > 0.5 else mix(color, "#FFFFFF", 0.14)
    return color


def ink(color, st):
    """Return (fill, stroke, stroke_width) for one glyph under a style."""
    sw, bg = st["_sw"], st["bg"]
    dark_bg = luminance(bg) < 0.5
    if st["fill"] == "solid":
        fill = contrast(color, bg, 0.10)
    elif st["fill"] == "tint":
        fill = mix(contrast(color, bg, 0.22), bg, 0.58)
    else:                                   # hollow
        fill = bg
    s = st["stroke"]
    if s is None:
        return fill, "none", 0.0
    if s == "auto":
        if st["fill"] == "solid":
            stroke = darken(color, 0.55) if not dark_bg else mix(color, "#FFFFFF", 0.45)
        else:
            # the outline IS the identity here, so it has to carry the colour
            stroke = contrast(color, bg, 0.34)
    else:
        stroke = s
    return fill, stroke, sw


def _sattr(stroke, sw, extra=""):
    if stroke == "none" or sw <= 0:
        return f'stroke="none"{extra}'
    return f'stroke="{stroke}" stroke-width="{sw}"{extra}'


def _cds(x, cy, w, color, direction, st):
    h = H * st["h"]
    top, bot = cy - h / 2, cy + h / 2
    head = min(HEAD, w * 0.5)
    pts = ([(x + w, top), (x + head, top), (x, cy), (x + head, bot), (x + w, bot)]
           if direction == "rev" else
           [(x, top), (x + w - head, top), (x + w, cy), (x + w - head, bot), (x, bot)])
    d = "M " + " L ".join(f"{px:.1f},{py:.1f}" for px, py in pts) + " Z"
    f, s, sw = ink(color, st)
    attrs = _sattr(s, sw, ' stroke-linejoin="round"')
    return f'<path d="{d}" fill="{f}" {attrs}/>'


def _box(x, cy, w, color, st, rx=None):
    h = H * st["h"]
    f, s, sw = ink(color, st)
    r = st["rx"] if rx is None else rx
    return (f'<rect x="{x:.1f}" y="{cy-h/2:.1f}" width="{w:.1f}" height="{h:.1f}" '
            f'rx="{r}" fill="{f}" {_sattr(s, sw)}/>')


def _tag(x, cy, w, color, st):
    h = H * st["h"]
    top = cy - h / 2
    f, s, sw = ink(color, st)
    base = st["bg"] if st["fill"] != "tint" else mix(color, st["bg"], 0.88)
    return (f'<rect x="{x:.1f}" y="{top:.1f}" width="{w:.1f}" height="{h:.1f}" rx="1" '
            f'fill="{base}" {_sattr(s if s != "none" else color, max(sw, 0.8))}/>'
            f'<rect x="{x+w*0.34:.1f}" y="{top+2:.1f}" width="{w*0.32:.1f}" '
            f'height="{h-4:.1f}" fill="{color}"/>')


def _loxp(x, cy, w, color, st, direction):
    h = H * st["h"]
    top, bot = cy - h / 2, cy + h / 2
    pts = ([(x + w, top), (x, cy), (x + w, bot)] if direction == "rev"
           else [(x, top), (x + w, cy), (x, bot)])
    d = "M " + " L ".join(f"{px:.1f},{py:.1f}" for px, py in pts) + " Z"
    f, s, sw = ink(color, st)
    attrs = _sattr(s, sw, ' stroke-linejoin="round"')
    return f'<path d="{d}" fill="{f}" {attrs}/>'


def _dome(x, cy, w, color, st):
    """Half circle sitting on the backbone - ribosome entry site, Kozak, IRES."""
    r = min(w, H * st["h"] * 1.1) / 2
    cx = x + w / 2
    f, so, sw = ink(color, st)
    d = (f'M {cx-r:.1f},{cy:.1f} A {r:.1f},{r:.1f} 0 0 1 {cx+r:.1f},{cy:.1f} Z')
    return f'<path d="{d}" fill="{f}" {_sattr(so, sw)}/>'


def _circle(x, cy, w, color, st, tick=False):
    """Origin of replication; with a tick, origin of transfer."""
    r = min(w, H * st["h"] * 0.8) / 2
    cx = x + w / 2
    f, so, sw = ink(color, st)
    out = (f'<circle cx="{cx:.1f}" cy="{cy:.1f}" r="{r:.1f}" fill="{f}" '
           f'{_sattr(so, sw)}/>')
    if tick:
        c = so if so != "none" else color
        out += (f'<path d="M {cx:.1f},{cy-r:.1f} V {cy-r-6:.1f} h 5" fill="none" '
                f'stroke="{c}" stroke-width="{max(sw,1.2):.1f}"/>')
    return out


def _cut(x, cy, w, color, st):
    """Restriction or protease site: a staggered cut through the backbone."""
    h = H * st["h"] / 2
    cx = x + w / 2
    c = contrast(color, st["bg"], 0.30)
    lw = max(st["_sw"], 1.2)
    return (f'<path d="M {cx-3:.1f},{cy-h:.1f} V {cy:.1f} H {cx+3:.1f} V {cy+h:.1f}" '
            f'fill="none" stroke="{c}" stroke-width="{lw:.1f}" '
            f'stroke-linejoin="round" stroke-linecap="round"/>')


def _chevron(x, cy, w, color, st, direction):
    """Primer binding site: a thin half arrow along the backbone."""
    c = contrast(color, st["bg"], 0.30)
    lw = max(st["_sw"], 1.2)
    y = cy - H * st["h"] * 0.22
    if direction == "rev":
        d = (f'M {x+w:.1f},{y:.1f} H {x:.1f} m 6,-4 l -6,4 l 6,4')
    else:
        d = (f'M {x:.1f},{y:.1f} H {x+w:.1f} m -6,-4 l 6,4 l -6,4')
    return (f'<path d="{d}" fill="none" stroke="{c}" stroke-width="{lw:.1f}" '
            f'stroke-linejoin="round" stroke-linecap="round"/>')


def _wave(x, cy, w, color, st):
    """Non-coding RNA: a sinusoid on the backbone."""
    c = contrast(color, st["bg"], 0.30)
    lw = max(st["_sw"] + 0.4, 1.4)
    a = H * st["h"] * 0.26
    n = max(2, int(w / 9))
    step = w / n
    d = [f'M {x:.1f},{cy:.1f}']
    for i in range(n):
        x0 = x + i * step
        up = -a if i % 2 == 0 else a
        d.append(f'Q {x0+step/2:.1f},{cy+up:.1f} {x0+step:.1f},{cy:.1f}')
    return (f'<path d="{" ".join(d)}" fill="none" stroke="{c}" '
            f'stroke-width="{lw:.1f}" stroke-linecap="round"/>')


def _stem(x, cy, w, color, st):
    """Stem loop: ribozyme, riboswitch, aptamer, attenuator."""
    rise = GLYPH_RISE["stem"] * st["h"]
    cx = x + w / 2
    r = min(w, 14) / 2 + 1
    c = contrast(color, st["bg"], 0.30)
    f, so, sw = ink(color, st)
    lw = max(st["_sw"], 1.3)
    return (f'<path d="M {cx:.1f},{cy:.1f} V {cy-rise+r:.1f}" fill="none" '
            f'stroke="{c}" stroke-width="{lw:.1f}"/>'
            f'<circle cx="{cx:.1f}" cy="{cy-rise+r:.1f}" r="{r:.1f}" fill="{f}" '
            f'{_sattr(so if so != "none" else c, max(sw, 1.0))}/>')


def _lollipop(x, cy, w, color, st):
    """Poly-A signal: a stalk with a filled head."""
    rise = GLYPH_RISE["lollipop"] * st["h"]
    cx = x + w / 2
    c = contrast(color, st["bg"], 0.30)
    lw = max(st["_sw"], 1.3)
    return (f'<path d="M {cx:.1f},{cy:.1f} V {cy-rise+4:.1f}" fill="none" '
            f'stroke="{c}" stroke-width="{lw:.1f}"/>'
            f'<circle cx="{cx:.1f}" cy="{cy-rise+4:.1f}" r="4.2" fill="{c}"/>')


def _hexagon(x, cy, w, color, st):
    """Operator / protein binding site / PAM."""
    h = H * st["h"] * 0.82 / 2
    k = min(w * 0.28, 8)
    f, so, sw = ink(color, st)
    pts = [(x+k, cy-h), (x+w-k, cy-h), (x+w, cy), (x+w-k, cy+h), (x+k, cy+h), (x, cy)]
    d = "M " + " L ".join(f"{a:.1f},{b:.1f}" for a, b in pts) + " Z"
    attrs = _sattr(so, sw, ' stroke-linejoin="round"')
    return f'<path d="{d}" fill="{f}" {attrs}/>'


def _bar(x, cy, w, color, st):
    """Assembly scar, junction, stop codon: a narrow upright bar."""
    h = H * st["h"]
    bw = max(w * 0.34, 3.5)
    f, so, sw = ink(color, st)
    return (f'<rect x="{x+(w-bw)/2:.1f}" y="{cy-h/2:.1f}" width="{bw:.1f}" '
            f'height="{h:.1f}" rx="1" fill="{f}" {_sattr(so, sw)}/>')


def _fence(x, cy, w, color, st):
    """Insulator: two uprights."""
    h = H * st["h"] / 2
    c = contrast(color, st["bg"], 0.30)
    lw = max(st["_sw"] + 0.4, 1.6)
    a, b = x + w * 0.3, x + w * 0.7
    return (f'<path d="M {a:.1f},{cy-h:.1f} V {cy+h:.1f} M {b:.1f},{cy-h:.1f} '
            f'V {cy+h:.1f}" fill="none" stroke="{c}" stroke-width="{lw:.1f}" '
            f'stroke-linecap="round"/>')


def _vee(x, cy, w, color, st):
    """Intron: a notch dipping below the backbone."""
    c = contrast(color, st["bg"], 0.30)
    lw = max(st["_sw"], 1.3)
    return (f'<path d="M {x:.1f},{cy:.1f} L {x+w/2:.1f},{cy+H*st["h"]*0.52:.1f} '
            f'L {x+w:.1f},{cy:.1f}" fill="none" stroke="{c}" '
            f'stroke-width="{lw:.1f}" stroke-linejoin="round"/>')


def _step(x, cy, w, color, st, direction):
    """Overhang / sticky end: offset strands."""
    c = contrast(color, st["bg"], 0.30)
    lw = max(st["_sw"] + 0.4, 1.6)
    g = H * st["h"] * 0.18
    if direction == "rev":
        d = f'M {x:.1f},{cy-g:.1f} H {x+w*0.6:.1f} M {x+w*0.4:.1f},{cy+g:.1f} H {x+w:.1f}'
    else:
        d = f'M {x:.1f},{cy-g:.1f} H {x+w:.1f} M {x:.1f},{cy+g:.1f} H {x+w*0.6:.1f}'
    return (f'<path d="{d}" fill="none" stroke="{c}" stroke-width="{lw:.1f}" '
            f'stroke-linecap="round"/>')


def _repeat(x, cy, w, color, st, direction):
    """LTR, ITR, transposon end: a box carrying its own direction."""
    h = H * st["h"]
    f, so, sw = ink(color, st)
    out = (f'<rect x="{x:.1f}" y="{cy-h/2:.1f}" width="{w:.1f}" height="{h:.1f}" '
           f'rx="1.5" fill="{f}" {_sattr(so, sw)}/>')
    c = so if so != "none" else contrast(color, st["bg"], 0.30)
    tipc = label_ink(color, st) if st["fill"] == "solid" else c
    m = cy
    for i in (0.3, 0.62):
        ax = x + w * i
        if direction == "rev":
            d = f'M {ax+5:.1f},{m-4.5:.1f} L {ax:.1f},{m:.1f} L {ax+5:.1f},{m+4.5:.1f}'
        else:
            d = f'M {ax:.1f},{m-4.5:.1f} L {ax+5:.1f},{m:.1f} L {ax:.1f},{m+4.5:.1f}'
        out += (f'<path d="{d}" fill="none" stroke="{tipc}" stroke-width="1.4" '
                f'stroke-linejoin="round" stroke-linecap="round"/>')
    return out


def _bracket(x, cy, w, color, st):
    """Engineered region, chromosomal locus, MCS: a span marker."""
    h = H * st["h"] / 2
    c = contrast(color, st["bg"], 0.30)
    lw = max(st["_sw"], 1.3)
    return (f'<path d="M {x:.1f},{cy+h:.1f} V {cy-h:.1f} H {x+w:.1f} V {cy+h:.1f}" '
            f'fill="none" stroke="{c}" stroke-width="{lw:.1f}" '
            f'stroke-linejoin="round"/>')


def _dashed(x, cy, w, color, st):
    """Unspecified part: a dashed outline."""
    h = H * st["h"]
    f, so, sw = ink(color, st)
    return (f'<rect x="{x:.1f}" y="{cy-h/2:.1f}" width="{w:.1f}" height="{h:.1f}" '
            f'rx="{st["rx"]}" fill="{f}" {_sattr(so, sw)} '
            f'stroke-dasharray="4 3"/>')


def _promoter(x, cy, color, direction, st):
    ph = PROM_H * st["h"]
    yu = cy - ph
    lw = st["_sw"] + 1 if st["_sw"] > 0 else 1.8
    if direction == "rev":
        line = (f'<path d="M {x+PROM_W:.1f},{cy:.1f} V {yu:.1f} H {x+6:.1f}" fill="none" '
                f'stroke="{color}" stroke-width="{lw}"/>')
        head = (f'<path d="M {x+6:.1f},{yu-5:.1f} L {x-2:.1f},{yu:.1f} '
                f'L {x+6:.1f},{yu+5:.1f} Z" fill="{color}"/>')
    else:
        line = (f'<path d="M {x:.1f},{cy:.1f} V {yu:.1f} H {x+PROM_W-6:.1f}" fill="none" '
                f'stroke="{color}" stroke-width="{lw}"/>')
        head = (f'<path d="M {x+PROM_W-6:.1f},{yu-5:.1f} L {x+PROM_W+2:.1f},{yu:.1f} '
                f'L {x+PROM_W-6:.1f},{yu+5:.1f} Z" fill="{color}"/>')
    return line + head


def _terminator(x, cy, color, st):
    ph = PROM_H * st["h"]
    yu = cy - ph
    lw = st["_sw"] + 1 if st["_sw"] > 0 else 1.8
    return (f'<path d="M {x+PROM_W/2:.1f},{cy:.1f} V {yu:.1f}" stroke="{color}" '
            f'stroke-width="{lw}" fill="none"/>'
            f'<path d="M {x:.1f},{yu:.1f} H {x+PROM_W:.1f}" stroke="{color}" '
            f'stroke-width="{lw}" fill="none"/>')


# --------------------------- helpers ---------------------------
def part_width(p, mode="none", px=11.0):
    default = default_size(p) or "M"
    if not is_scalable(p):
        # a position marker is drawn at one canonical width, whatever the
        # sheet says, because a wider one would assert a longer feature
        return SIZE_W[default]
    w = SIZE_W.get(p.get("size") or default, SIZE_W[default])
    if inside_ok(p, mode):
        need = text_width(p["label"], px) + 2 * LABEL_PAD
        if glyph_of(p) == "arrow":
            need += HEAD                      # the arrowhead is not writable
        w = max(w, need)
    return w


def part_color(p, resolved):
    if p.get("color"):
        return p["color"]
    return resolved.get((p["type"], p.get("label", "")), NEUTRAL)


def draw_part(p, x, cy, resolved, st, w=None, mode="none", px=11.0,
              show_label=True):
    g, d = glyph_of(p), p.get("dir", "fwd")
    c = part_color(p, resolved)
    if g in RISER_GLYPHS or g in LINE_GLYPHS:
        c = contrast(c, st["bg"], 0.30)      # thin strokes need more separation
    if w is None:
        w = part_width(p, mode, px)
    shadow = ' filter="url(#soft)"' if st.get("shadow") else ""
    draw = {
        "box":      lambda: _box(x, cy, w, c, st),
        "arrow":    lambda: _cds(x, cy, w, c, d, st),
        "tag":      lambda: _tag(x, cy, w, c, st),
        "tri":      lambda: _loxp(x, cy, w, c, st, d),
        "spark":    lambda: _promoter(x, cy, c, d, st),
        "tee":      lambda: _terminator(x, cy, c, st),
        "dome":     lambda: _dome(x, cy, w, c, st),
        "circle":   lambda: _circle(x, cy, w, c, st),
        "circle_t": lambda: _circle(x, cy, w, c, st, tick=True),
        "cut":      lambda: _cut(x, cy, w, c, st),
        "chevron":  lambda: _chevron(x, cy, w, c, st, d),
        "wave":     lambda: _wave(x, cy, w, c, st),
        "stem":     lambda: _stem(x, cy, w, c, st),
        "lollipop": lambda: _lollipop(x, cy, w, c, st),
        "hex":      lambda: _hexagon(x, cy, w, c, st),
        "bar":      lambda: _bar(x, cy, w, c, st),
        "fence":    lambda: _fence(x, cy, w, c, st),
        "vee":      lambda: _vee(x, cy, w, c, st),
        "step":     lambda: _step(x, cy, w, c, st, d),
        "repeat":   lambda: _repeat(x, cy, w, c, st, d),
        "bracket":  lambda: _bracket(x, cy, w, c, st),
        "dashed":   lambda: _dashed(x, cy, w, c, st),
    }.get(g, lambda: _box(x, cy, w, c, st))
    out = draw()
    if shadow:
        out = f'<g{shadow}>{out}</g>'
    if inside_ok(p, mode) and show_label:
        # centre on the body, not the bounding box: the arrowhead is dead space
        body = w - (HEAD if g == "arrow" else 0)
        tx = x + (body / 2 + HEAD if d == "rev" and g == "arrow" else body / 2)
        out += (f'<text x="{tx:.1f}" y="{cy + px * 0.35:.1f}" text-anchor="middle" '
                f'font-size="{px:.1f}" font-family="{st["font"]}" '
                f'fill="{label_ink(part_color(p, resolved), st)}">{esc(p["label"])}</text>')
    return out


def esc(t):
    return (str(t).replace("&", "&amp;").replace("<", "&lt;").replace(">", "&gt;"))


def construct_width(parts, mode="none", px=11.0):
    w = 0
    for i, p in enumerate(parts):
        if i > 0 and not p.get("join"):
            w += GAP
        w += part_width(p, mode, px)
    return w


def plan_outside(parts, xs, widths, st, mode, px, allow=None):
    """Assign each outside label to the lowest tier where it does not touch
    its neighbour. Returns [(part, centre_x, tier)] and the tier count."""
    placed, right = [], []
    for i, (p, x, w) in enumerate(zip(parts, xs, widths)):
        if not outside_needed(p, mode):
            continue
        if allow is not None and not allow[i]:
            continue
        cx = x + w / 2
        half = text_width(p["label"], px) / 2
        t = 0
        while t < len(right) and cx - half < right[t] + 6:
            t += 1
        if t == len(right):
            right.append(cx + half)
        else:
            right[t] = cx + half
        placed.append((p, cx, t))
    return placed, len(right)


def legend_label(p):
    return p.get("label") or p["type"].replace("_", " ").capitalize()


def legend_offset(p, slot_w, st):
    """Promoters and terminators hang above and to one side of their anchor -
    right on a cassette, floating in a legend. Centre their real ink."""
    g = glyph_of(p)
    if g not in GLYPH_RISE:
        return 0.0, 0.0
    lw = (st["_sw"] + 1) if st["_sw"] > 0 else 1.8
    rise = GLYPH_RISE[g] * st["h"]
    if g == "spark":
        top, bot, left, right = -rise, lw / 2, -lw / 2, PROM_W + 2
    elif g == "tee":
        top, bot, left, right = -(rise + lw / 2), lw / 2, 0.0, PROM_W
    else:
        top, bot, left, right = -rise, lw / 2, 0.0, slot_w
    return (slot_w - (right - left)) / 2 - left, -(top + bot) / 2


# --------------------------- legend ---------------------------
def build_legend(constructs, x0, y0, wrap_w, resolved, st, font_px=BASE_FONT_PX):
    seen, items = set(), []
    for c in constructs:
        for p in c["parts"]:
            key = (p["type"], p.get("label", ""))
            if key not in seen:
                seen.add(key)
                items.append(p)
    CHAR, PAD = 0.56 * font_px, 26
    GLYW = SIZE_W[LEGEND_GLYPH]
    row_h = max(H * st["h"], PROM_H * st["h"], font_px) + 14
    svg, x, y, used_w = [], x0, y0 + row_h / 2, x0
    for p in items:
        label = legend_label(p)
        entry_w = GLYW + 8 + len(label) * CHAR + PAD
        if x > x0 and x + entry_w > x0 + wrap_w:
            x, y = x0, y + row_h
        dx, dy = legend_offset(p, GLYW, st)
        svg.append(draw_part({**p, "size": LEGEND_GLYPH}, x + dx, y + dy,
                             resolved, st, w=GLYW))   # mode stays "none" here
        svg.append(f'<text x="{x+GLYW+8:.0f}" y="{y+font_px*0.34:.0f}" '
                   f'font-size="{font_px:.1f}" font-family="{st["font"]}" '
                   f'fill="{st["text"]}">{esc(label)}</text>')
        x += entry_w
        used_w = max(used_w, x)
    return "".join(svg), (y - y0) + row_h, used_w


# --------------------------- render ---------------------------
def build_figure(constructs, settings, resolved, st, outfile=None,
                 show_legend=None, write=True):
    width_cm = settings["figure_width_cm"]
    height_cm = settings["figure_height_cm"]
    anchor = str(settings["anchor_side"]).lower()
    if anchor not in ("left", "right"):
        raise SystemExit(f"anchor_side must be 'left' or 'right', got {anchor!r}")
    row_h = settings["cassette_spacing"]
    min_font_pt = settings["min_font_pt"]
    st = dict(st)
    st["_sw"] = settings["line_thickness"] * st["stroke_w"]
    backbone = settings["backbone_thickness"] * st["bb_w"]
    mode = str(settings.get("labels") or "none").strip().lower()
    if mode not in ("none", "inside", "outside", "below"):
        raise SystemExit("labels must be none, inside, outside or below")
    lpx = float(settings.get("label_pt") or 11.0)
    if outfile is None:
        outfile = settings["outfile"]

    if show_legend is None:
        sl = settings["show_legend"]
        if isinstance(sl, str) and sl.strip().lower() in ("", "auto"):
            # named glyphs do not need a key; an unnamed figure does
            show_legend = (mode == "none")
        else:
            show_legend = _as_bool(sl, True)

    max_w = max(construct_width(c["parts"], mode, lpx) for c in constructs)

    # The legend font is solved iteratively: a bigger font widens the legend,
    # which widens the canvas, which (to hold min_font_pt) demands a bigger
    # font again. Below a certain figure width that loop runs away, so the
    # font is capped and the sanity check reports it rather than emitting a
    # canvas millions of units wide.
    font_px, leg_w, leg_h, leg_svg = BASE_FONT_PX, 0, 0, ""
    font_cap = BASE_FONT_PX * FONT_RUNAWAY
    for _ in range(8):
        if show_legend:
            leg_svg, leg_h, leg_w = build_legend(constructs, LEFT, MARGIN, max_w,
                                                 resolved, st, font_px)
        natW_est = max(LEFT + max_w + MARGIN, leg_w + MARGIN)
        need = (min_font_pt * natW_est / (width_cm * PT_PER_CM)) if (width_cm and show_legend) else BASE_FONT_PX
        new_px = min(max(BASE_FONT_PX, need), font_cap)
        if abs(new_px - font_px) < 0.3:
            font_px = new_px
            break
        font_px = new_px

    body, y = [], MARGIN
    max_pitch = 0.0
    if show_legend:
        body.append(leg_svg)
        y += leg_h + 18
    rtitle = str(settings.get("row_titles") or "none").strip().lower()
    if rtitle not in ("none", "left", "above"):
        raise SystemExit("row_titles must be none, left or above")
    tpx = lpx * 1.05
    left = LEFT
    if rtitle == "left":
        left = LEFT + max(text_width(c.get("name", ""), tpx) for c in constructs) + 14

    repeat = str(settings.get("label_repeat") or "all").strip().lower()
    if repeat not in ("all", "once", "row"):
        raise SystemExit("label_repeat must be all, once or row")
    seen = set()

    tier_h = lpx + TIER_GAP
    # An outside label is centred on its glyph, so one on the first or last
    # part hangs past the backbone. Track how far, and widen (or shift) the
    # canvas afterwards - otherwise the name is simply cut off at the edge.
    lab_l, lab_r = float("inf"), 0.0
    for it in constructs:
        parts = it["parts"]
        cw = construct_width(parts, mode, lpx)
        x0 = left + (max_w - cw if anchor == "right" else 0)

        xs, widths, x = [], [], x0
        for i, p in enumerate(parts):
            if i > 0 and not p.get("join"):
                x += GAP
            w = part_width(p, mode, lpx)
            xs.append(x)
            widths.append(w)
            x += w

        if repeat == "row":
            seen = set()
        allow = []
        for p in parts:
            key = (p["type"], p.get("label", ""))
            if repeat == "all" or not p.get("label"):
                allow.append(True)
            else:
                allow.append(key not in seen)
                seen.add(key)

        placed, ntiers = plan_outside(parts, xs, widths, st, mode, lpx, allow)
        stack = (ntiers * tier_h + 8) if ntiers else 0
        above = stack if mode != "below" else 0
        below = stack if mode == "below" else 0
        ink_top = max(top_ink(p, st) for p in parts)
        ink_bot = H * st["h"] / 2
        title_h = (tpx + 9) if rtitle == "above" else 0
        # above = title_h = 0 reproduces the original row geometry exactly
        cy = y + title_h + above + ink_top + 17
        pitch = max(row_h, title_h + above + ink_top + 17 + ink_bot + below + 12)

        dash = f' stroke-dasharray="{st["dash"]}"' if st["dash"] else ""
        bb = st["bb"] if st["bb"] != "auto" else st["text"]
        body.append(f'<line x1="{x0:.1f}" y1="{cy:.1f}" x2="{x0+cw:.1f}" y2="{cy:.1f}" '
                    f'stroke="{bb}" stroke-width="{backbone}"{dash}/>')
        for p, px_, w, ok in zip(parts, xs, widths, allow):
            body.append(draw_part(p, px_, cy, resolved, st, w=w, mode=mode,
                                  px=lpx, show_label=ok))

        if rtitle == "left":
            body.append(
                f'<text x="{left-14:.1f}" y="{cy + tpx*0.35:.1f}" text-anchor="end" '
                f'font-size="{tpx:.1f}" font-family="{st["font"]}" font-weight="600" '
                f'fill="{st["text"]}">{esc(it.get("name",""))}</text>')
        elif rtitle == "above":
            body.append(
                f'<text x="{x0:.1f}" y="{cy - ink_top - above - 7:.1f}" '
                f'font-size="{tpx:.1f}" font-family="{st["font"]}" font-weight="600" '
                f'fill="{st["text"]}">{esc(it.get("name",""))}</text>')

        down = (mode == "below")
        base = (cy + ink_bot + 7 + lpx * 0.8) if down else (cy - ink_top - 7)
        for p, cx, tier in placed:
            ty = base + tier * tier_h if down else base - tier * tier_h
            if tier:        # a leader keeps an offset label tied to its glyph
                y2 = (cy + ink_bot + 2) if down else (cy - top_ink(p, st) - 2)
                y1 = (ty - lpx * 0.8) if down else (ty + 3)
                body.append(f'<line x1="{cx:.1f}" y1="{y1:.1f}" x2="{cx:.1f}" '
                            f'y2="{y2:.1f}" stroke="{st["text"]}" '
                            f'stroke-width="0.7" opacity="0.45"/>')
            body.append(f'<text x="{cx:.1f}" y="{ty:.1f}" text-anchor="middle" '
                        f'font-size="{lpx:.1f}" font-family="{st["font"]}" '
                        f'fill="{st["text"]}">{esc(p["label"])}</text>')
            half = text_width(p["label"], lpx) / 2
            lab_l = min(lab_l, cx - half)
            lab_r = max(lab_r, cx + half)
        max_pitch = max(max_pitch, pitch)
        y += pitch

    pad_l = max(0.0, MARGIN - lab_l) if lab_l != float("inf") else 0.0
    if pad_l:
        body = [f'<g transform="translate({pad_l:.1f},0)">'] + body + ["</g>"]
    natW = max(left + max_w + MARGIN, leg_w + MARGIN, lab_r + MARGIN) + pad_l
    natH = y + MARGIN
    if width_cm and height_cm:
        size = f'width="{width_cm}cm" height="{height_cm}cm"'
    elif width_cm:
        size = f'width="{width_cm}cm" height="{width_cm*natH/natW:.3f}cm"'
    else:
        size = f'width="{natW:.0f}" height="{natH:.0f}"'

    defs = ('<defs><filter id="soft" x="-20%" y="-40%" width="140%" height="190%">'
            '<feDropShadow dx="0" dy="1.4" stdDeviation="1.6" flood-opacity="0.22"/>'
            '</filter></defs>') if st.get("shadow") else ""
    svg = (f'<svg xmlns="http://www.w3.org/2000/svg" {size} '
           f'viewBox="0 0 {natW:.0f} {natH:.0f}" preserveAspectRatio="xMidYMid meet">'
           f'{defs}<rect width="{natW:.0f}" height="{natH:.0f}" fill="{st["bg"]}"/>'
           + "".join(body) + "</svg>")

    basedir = settings.get("_basedir") or SCRIPT_DIR
    outpath = outfile if os.path.isabs(outfile) else os.path.join(basedir, outfile)
    # --check wants the geometry, not a file. Writing one and deleting it
    # afterwards failed silently wherever the folder refuses deletes, which
    # left a stray dotfile behind.
    if write:
        os.makedirs(os.path.dirname(outpath) or ".", exist_ok=True)
        with open(outpath, "w") as fh:
            fh.write(svg)
    return (outpath, natW, natH, (font_px if show_legend else None), leg_h,
            max_pitch / max(row_h, 1))


def export_each(constructs, settings, resolved, st):
    prefix = settings["export_prefix"]
    s = dict(settings)
    s["figure_width_cm"] = settings["export_width_cm"]
    s["figure_height_cm"] = None
    for i, c in enumerate(constructs, 1):
        safe = "".join(ch if (ch.isalnum() or ch in "-_") else "_" for ch in c.get("name", str(i)))
        p, *_ = build_figure([c], s, resolved, st, outfile=f"{prefix}_{safe}.svg",
                             show_legend=False)
        print(f"wrote {p}")


# ------------------------ colour-vision checking ------------------------
# Dependency-free: simulate the two common forms of colour-blindness and
# measure how far apart the figure's colours still are. Approximate by
# design - it exists to raise a flag, not to grade a palette.

def _srgb_to_lin(c):
    c = c / 255.0
    return c / 12.92 if c <= 0.04045 else ((c + 0.055) / 1.055) ** 2.4


def _lin_to_lab(r, g, b):
    x = (0.4124 * r + 0.3576 * g + 0.1805 * b) / 0.95047
    y = (0.2126 * r + 0.7152 * g + 0.0722 * b)
    z = (0.0193 * r + 0.1192 * g + 0.9505 * b) / 1.08883

    def f(t):
        return t ** (1 / 3) if t > 0.008856 else (7.787 * t + 16 / 116)

    fx, fy, fz = f(max(x, 0)), f(max(y, 0)), f(max(z, 0))
    return 116 * fy - 16, 500 * (fx - fy), 200 * (fy - fz)


# Machado, Oliveira & Fernandes (2009), severity 1.0, applied in linear RGB.
# Checked against colour-science's simulation on pairs known to collide: it
# scores those 0.3-9 where clearly safe pairs land above 40, which is what
# the threshold below relies on. An older Brettel-style approximation was
# tried first and scored known-bad pairs at 16-82 - it would have stayed
# silent on real collisions.
_CVD = {
    "deuteranopia": ((0.367322, 0.860646, -0.227968),
                     (0.280085, 0.672501, 0.047413),
                     (-0.011820, 0.042940, 0.968881)),
    "protanopia": ((0.152286, 1.052583, -0.204868),
                   (0.114503, 0.786281, 0.099216),
                   (-0.003882, -0.048116, 1.051998)),
}
# CIE76 thresholds. Deliberately conservative: a warning nobody trusts is
# worse than one that occasionally stays quiet, so this errs toward silence.
CVD_CLASH = 15.0
SAME_COLOUR = 12.0


def _lab_under(hexv, kind=None):
    r, g, b = (_srgb_to_lin(float(v)) for v in _rgb(hexv))
    if kind:
        m = _CVD[kind]
        r, g, b = (m[i][0] * r + m[i][1] * g + m[i][2] * b for i in range(3))
    return _lin_to_lab(r, g, b)


_LAB_CACHE = {}


def _lab_cached(hexv, kind=None):
    key = (hexv, kind)
    v = _LAB_CACHE.get(key)
    if v is None:
        v = _lab_under(hexv, kind)
        _LAB_CACHE[key] = v
    return v


def _lab_gap(la, lb):
    return ((la[0] - lb[0]) ** 2 + (la[1] - lb[1]) ** 2
            + (la[2] - lb[2]) ** 2) ** 0.5


def colour_distance(a, b, kind=None):
    """CIE76 distance. Below about 12 reads as one colour at glyph size."""
    return _lab_gap(_lab_cached(a, kind), _lab_cached(b, kind))


# --------------------------- sanity check ---------------------------
def fit_warnings(constructs, settings, st, natW, natH, legend_px, leg_h,
                 pitch_ratio=1.0, resolved=None):
    """Everything here is about the gap between the drawing's own units and
    the physical size you asked for. The SVG always *renders*; the question
    is whether anyone can read it once it is that many centimetres wide."""
    warn = []
    wcm, hcm = settings["figure_width_cm"], settings["figure_height_cm"]
    mode = str(settings.get("labels") or "none").strip().lower()
    lpx = float(settings.get("label_pt") or 11.0)
    floor_pt = float(settings.get("min_label_pt") or 6.0)

    if not wcm:
        return warn                       # natural size: nothing is being squeezed

    # points per viewBox unit, after any letterboxing
    scale = scale_w = wcm * PT_PER_CM / natW
    height_binds = False
    if hcm:
        scale_h = hcm * PT_PER_CM / natH
        height_binds = scale_h < scale_w
        scale = min(scale_w, scale_h)
        nat_h_cm = wcm * natH / natW
        if hcm < nat_h_cm - 0.05:
            warn.append(
                f"figure_height_cm {hcm} is shorter than this drawing needs "
                f"({nat_h_cm:.2f} cm at {wcm} cm wide), so everything is shrunk "
                f"to fit and you get blank margins at the sides. Leave "
                f"figure_height_cm blank, or set it to {nat_h_cm:.2f}.")

    # 1. glyph labels too small to read
    if mode != "none":
        eff = lpx * scale
        if eff < floor_pt:
            need_scale = floor_pt / lpx
            need_px = floor_pt / scale
            # name whichever dimension is actually holding the drawing back
            if height_binds:
                dim = (f"raise figure_height_cm to "
                       f"{need_scale * natH / PT_PER_CM:.1f} cm "
                       f"(it, not the width, is what is limiting this)")
            else:
                dim = (f"widen figure_width_cm to "
                       f"{need_scale * natW / PT_PER_CM:.1f} cm")
            warn.append(
                f"glyph labels render at {eff:.1f} pt, under your "
                f"min_label_pt of {floor_pt:.0f}. Fixes, any one of: {dim}; "
                f"raise label_pt to {need_px:.0f}; or shorten the names.")

    # 2a. the legend font hit its cap, i.e. min_font_pt is unreachable here
    if legend_px and legend_px >= BASE_FONT_PX * FONT_RUNAWAY - 0.5:
        reachable = legend_px * scale
        warn.append(
            f"min_font_pt {settings['min_font_pt']:.0f} is unreachable at "
            f"figure_width_cm {wcm}: the legend would have to grow without "
            f"limit, so it was capped and renders at about {reachable:.1f} pt. "
            f"Widen the figure, lower min_font_pt, or set show_legend to FALSE "
            f"and use labels instead.")

    # 2. the legend has been inflated until it eats the figure
    if legend_px and leg_h:
        frac = leg_h / max(natH - leg_h, 1)      # legend vs the cassettes
        if frac > 0.55:
            warn.append(
                f"the legend is {frac*100:.0f}% as tall as the cassettes - "
                f"min_font_pt {settings['min_font_pt']:.0f} forces it that big "
                f"at {wcm} cm. Widen figure_width_cm to about "
                f"{wcm*1.8:.0f} cm, or set labels to outside and show_legend "
                f"to auto so the names go on the glyphs instead.")

    # 3. an inside label has overridden the size you chose
    if mode == "inside":
        bad = []
        for c in constructs:
            for p in c["parts"]:
                if not inside_ok(p, mode):
                    continue
                nominal = SIZE_W.get(p.get("size") or default_size(p) or "M",
                                     SIZE_W["M"])
                actual = part_width(p, mode, lpx)
                if actual > nominal * 1.25:
                    bad.append((p["label"], p.get("size") or "M",
                                nominal, actual))
        if bad:
            seen, uniq = set(), []
            for b in bad:
                if b[0] not in seen:
                    seen.add(b[0])
                    uniq.append(b)
            names = ", ".join(f"{n} ({sz}: {nm:.0f}->{ac:.0f})"
                              for n, sz, nm, ac in uniq[:4])
            more = f" and {len(uniq)-4} more" if len(uniq) > 4 else ""
            warn.append(
                f"inside labels are wider than the size you set, so these "
                f"glyphs were stretched past it: {names}{more}. Lower "
                f"label_pt, use labels = outside, or set a larger size.")

    # 3b. a size set on a position marker, which cannot honour it
    ignored = []
    for c in constructs:
        for p in c["parts"]:
            # only worth saying when the requested size would have changed
            # something; writing XS on a part that is XS anyway is harmless
            if (p.get("size") and not is_scalable(p)
                    and SIZE_W.get(p["size"]) != SIZE_W.get(default_size(p))):
                ignored.append((p["label"] or p["type"], p["type"]))
    if ignored:
        seen, uniq = set(), []
        for lab, t in ignored:
            if t not in seen:
                seen.add(t)
                uniq.append(f"{lab} ({t})")
        warn.append(
            f"size is set on {len(ignored)} position marker(s) and was "
            f"ignored: {', '.join(uniq[:4])}"
            f"{f' and {len(uniq)-4} more' if len(uniq) > 4 else ''}. "
            f"These mark a point in the sequence, so they draw at one fixed "
            f"width; only length-bearing parts (cds, homology_arm, ltr, ...) "
            f"respond to XS/S/M/L.")

    # 3c. colours that collapse for a colour-blind reader, or that are too
    # close for anyone. Only the parts actually in this figure are compared,
    # and only when colour is doing the work: if every glyph carries its own
    # name and there is no legend to match against, two parts sharing a
    # colour costs the reader nothing, and warning about it is noise.
    colour_is_key = (mode == "none") or bool(legend_px)
    used = {}
    for c in constructs:
        for p in c["parts"]:
            if resolved is None:
                break
            used.setdefault(part_color(p, resolved), set()).add(
                p.get("label") or p["type"])
    cols = sorted(used)
    same, cvd = [], []
    for i in range(len(cols)):
        for j in range(i + 1, len(cols)):
            a, b = cols[i], cols[j]
            na = ", ".join(sorted(used[a])[:2])
            nb = ", ".join(sorted(used[b])[:2])
            if colour_distance(a, b) < SAME_COLOUR:
                same.append((na, nb))
                continue
            if min(colour_distance(a, b, k) for k in _CVD) < CVD_CLASH:
                cvd.append((na, nb))
    if same and colour_is_key:
        pairs = "; ".join(f"{x} vs {y}" for x, y in same[:3])
        warn.append(
            f"{len(same)} pair(s) of parts are nearly the same colour: {pairs}"
            f"{f' and {len(same)-3} more' if len(same) > 3 else ''}. Pin one of "
            f"each pair in the colors sheet, or pick a palette with more range.")
    if cvd and colour_is_key:
        pairs = "; ".join(f"{x} vs {y}" for x, y in cvd[:3])
        warn.append(
            f"{len(cvd)} pair(s) of parts become indistinguishable to a "
            f"red-green colour-blind reader: {pairs}"
            f"{f' and {len(cvd)-3} more' if len(cvd) > 3 else ''}. Roughly 1 in "
            f"12 men is affected. palette = okabe-ito, tol-muted or cividis "
            f"avoids it, or name the glyphs with labels = outside.")

    # 4. more distinct parts than the palette has colours
    keys = {(p["type"], p.get("label", "")) for c in constructs for p in c["parts"]}
    _, pal, _, pname = resolve_theme(settings)
    # Reported whatever the mode, because the palette does the colouring
    # unless every single part is pinned. Gating this on palette_mode meant
    # the common case - no pins at all - was never told anything.
    # report what actually happened, not what was predicted: the palette is
    # extended with tints and shades first, and only genuinely runs out past
    # that point
    if resolved is not None:
        auto = [v for k, v in resolved.items() if k in keys]
        dups = len(auto) - len(set(auto))
        bigger = (f"spectrum has {len(PALETTES['spectrum'])}, "
                  f"vivid {len(PALETTES['vivid'])}")
        if dups:
            warn.append(
                f"{len(keys)} distinct parts is more than any palette can "
                f"separate - {dups} of them share a colour with another part "
                f"and cannot be told apart. Use labels = outside so each glyph "
                f"carries its own name; colour stops working as an identifier "
                f"somewhere around a dozen categories.")
        elif len(keys) > len(pal):
            warn.append(
                f"{len(keys)} distinct parts but palette '{pname}' has only "
                f"{len(pal)} colours, so {len(keys) - len(pal)} are drawn as "
                f"tints and shades of it. They stay distinguishable, but a "
                f"palette with more hues reads better: {bigger}.")

    # 5. a row so tall the labels dominate it. This compares the real row
    # pitch, not canvas height over row count - the latter counts the page
    # margins and cried wolf on single-cassette figures.
    if mode in ("outside", "below"):
        ratio = pitch_ratio
        if ratio > 1.45:
            warn.append(
                f"outside labels are stacking into tiers - rows are {ratio:.1f}x "
                f"the cassette_spacing you set. Lower label_pt, widen "
                f"figure_width_cm so names have room side by side, or set "
                f"label_repeat to once so repeats stop competing for space.")
    return warn


# --------------------------- export ---------------------------
def convert(svg_path, target):
    """SVG is the deliverable; .png / .pdf are a convenience on top."""
    ext = os.path.splitext(target)[1].lower()
    if ext == ".svg":
        return None
    try:
        import cairosvg
    except ImportError:
        raise SystemExit(
            f"Writing {ext} needs cairosvg:  python3 -m pip install cairosvg\n"
            f"(the SVG itself was written to {svg_path})")
    if ext == ".png":
        cairosvg.svg2png(url=svg_path, write_to=target, scale=4)
    elif ext == ".pdf":
        cairosvg.svg2pdf(url=svg_path, write_to=target)
    else:
        raise SystemExit(f"Cannot write {ext}. Use .svg, .png or .pdf.")
    return target


