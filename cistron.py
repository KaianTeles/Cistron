def _build_aliases():
    """Alias -> canonical type. A clash would silently route a part to the
    wrong glyph, so it raises at import instead."""
    out = {}
    def put(key, name):
        if key in out and out[key] != name:
            raise RuntimeError(
                f"PART_TYPES alias clash: {key!r} maps to both "
                f"{out[key]!r} and {name!r}")
        out[key] = name
    for name, spec in PART_TYPES.items():
        put(name, name)
        put(name.replace("_", " "), name)
        for a in spec.get("aliases", ()):
            put(a, name)
    return out


ALIASES = _build_aliases()


